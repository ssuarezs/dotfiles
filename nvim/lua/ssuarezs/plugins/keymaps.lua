local map = vim.keymap.set

map("n", "]]", function()
	Snacks.words.jump(vim.v.count1)
end, { desc = "Next reference" })
map("n", "[[", function()
	Snacks.words.jump(-vim.v.count1)
end, { desc = "Previous reference" })

map("n", ";f", function()
	Snacks.picker.files({ hidden = true })
end, { desc = "Find files" })
map("n", ";r", function()
	Snacks.picker.grep({ hidden = true })
end, { desc = "Live grep" })
map("n", ";;", function()
	Snacks.picker.resume()
end, { desc = "Resume picker" })
local function pick_buffers()
	Snacks.picker.buffers({ jump = { reuse_win = true } })
end
map("n", ";b", pick_buffers, { desc = "Buffers" })
map("n", ";e", function()
	Snacks.picker.diagnostics()
end, { desc = "Diagnostics" })
map("n", ";n", function()
	Snacks.picker.notifications()
end, { desc = "Notification history" })
map("n", ";h", function()
	Snacks.picker.git_diff()
end, { desc = "Git hunks" })

map("n", "gd", function()
	Snacks.picker.lsp_definitions()
end, { desc = "Go to definition" })
map("n", "gD", function()
	Snacks.picker.lsp_declarations()
end, { desc = "Go to declaration" })
map("n", "gy", function()
	Snacks.picker.lsp_type_definitions()
end, { desc = "Go to type definition" })
map("n", "gr", function()
	Snacks.picker.lsp_references()
end, { desc = "References", nowait = true })
map("n", "gI", ssuarezs.lsp.goto_source_definition, { desc = "Go to source definition / implementation" })
map("n", ";c", function()
	Snacks.picker.lsp_incoming_calls()
end, { desc = "Incoming calls" })
map("n", "K", vim.lsp.buf.hover, { desc = "Hover" })
map("n", "gK", vim.lsp.buf.signature_help, { desc = "Signature help" })
map("i", "<C-k>", vim.lsp.buf.signature_help, { desc = "Signature help" })
map("n", "<C-j>", function()
	vim.diagnostic.jump({ count = 1, float = true })
end, { desc = "Next diagnostic" })
map({ "n", "x" }, "<leader>ca", vim.lsp.buf.code_action, { desc = "Code action" })
map("n", "<leader>cr", vim.lsp.buf.rename, { desc = "Rename symbol" })
map("n", "<leader>cR", function()
	Snacks.rename.rename_file()
end, { desc = "Rename file" })
map({ "n", "x" }, "<leader>f", function()
	require("conform").format({ async = true })
end, { desc = "Format buffer" })
map("n", "<leader>cl", "<cmd>checkhealth vim.lsp<cr>", { desc = "LSP info" })

map("n", "<leader>gb", function()
	require("gitsigns").blame_line()
end, { desc = "Blame line" })
map("n", "<leader>gB", function()
	require("gitsigns").blame()
end, { desc = "Blame buffer" })
map("n", "<leader>go", ssuarezs.git.open_line_revision, { desc = "Open line revision in new tab" })
map("n", "<leader>gs", ssuarezs.git.toggle_buffer_stage, { desc = "Stage/unstage buffer" })
map("n", "<leader>gh", function()
	require("gitsigns").stage_hunk()
end, { desc = "Stage/unstage hunk" })
map("n", "<leader>gd", function()
	MiniDiff.toggle_overlay()
end, { desc = "Toggle diff overlay" })
map("n", "<leader>dv", ssuarezs.git.toggle_codediff, { desc = "Toggle diff view" })
map("n", "<leader>dh", "<cmd>CodeDiff history %<cr>", { desc = "File history" })
map("n", "<leader>dH", "<cmd>CodeDiff history<cr>", { desc = "Repository history" })
map("n", ";g", ssuarezs.git.open_lazygit, { desc = "Lazygit" })

map("n", "sf", function()
	require("oil").open_float(nil, { preview = {} })
end, { desc = "File explorer" })
